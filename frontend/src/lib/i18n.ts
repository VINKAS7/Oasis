const MESSAGES: Record<Lang, Record<MessageKey, string>> = { en, fr, it, de };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  const text = MESSAGES[lang][key] ?? en[key];
  return vars ? text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : text;
}

/** The current language and its translate function; re-renders when the visitor switches. */
export function useT(): { lang: Lang; t: Translate } {
  const lang = useSyncExternalStore(subscribe, () => current);
  return { lang, t: (key, vars) => translate(lang, key, vars) };
}
