/** The customer-facing pages' languages. The choice is kept in this browser under oasis.lang,
 *  the same key the MCP landing page (/mcp) reads. */
export type Lang = "en" | "fr" | "it" | "de";
export const LANGS: { code: Lang; label: string }[] = [
  { code: "en", label: "English" },
  { code: "fr", label: "Français" },
  { code: "it", label: "Italiano" },
  { code: "de", label: "Deutsch" },
];
const KEY = "oasis.lang";
const isLang = (v: unknown): v is Lang => v === "en" || v === "fr" || v === "it" || v === "de";

/** The saved choice, else the browser's first supported language, else English. */
function detect(): Lang {
  const saved = localStorage.getItem(KEY);
  if (isLang(saved)) return saved;
  for (const l of navigator.languages ?? [navigator.language]) {
    const code = l.slice(0, 2).toLowerCase();
    if (isLang(code)) return code;
  }
  return "en";
}

let current: Lang = detect();
document.documentElement.lang = current;
const listeners = new Set<() => void>();

export function setLang(lang: Lang): void {
  current = lang;
  localStorage.setItem(KEY, lang);
  document.documentElement.lang = lang;
  listeners.forEach((l) => l());
}

const subscribe = (l: () => void) => (listeners.add(l), () => void listeners.delete(l));

